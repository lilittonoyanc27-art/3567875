export function shuffleArray<T>(items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

export function prepareQuestionOptions(
  q: Question,
  targetCorrectIndex?: number
): Question {
  if (q.mode === 'viaje') {
    return q;
  }
  const shuffled = shuffleArray(q.options);
  if (
    targetCorrectIndex !== undefined &&
    targetCorrectIndex >= 0 &&
    targetCorrectIndex < shuffled.length
  ) {
    const currentIdx = shuffled.findIndex((o) => o.id === q.correctOptionId);
    if (currentIdx !== -1 && currentIdx !== targetCorrectIndex) {
      [shuffled[currentIdx], shuffled[targetCorrectIndex]] = [
        shuffled[targetCorrectIndex],
        shuffled[currentIdx],
      ];
    }
  }
  return {
    ...q,
    options: shuffled,
  };
}

function difficultyRank(d: DifficultyLevel): number {
  return d === 'facil' ? 0 : d === 'medio' ? 1 : 2;
}

function sortByTargetDifficulty(
  pool: Question[],
  preferred: DifficultyLevel
): Question[] {
  const rankTarget = difficultyRank(preferred);
  return [...pool].sort((a, b) => {
    const da = Math.abs(difficultyRank(a.difficulty) - rankTarget);
    const db = Math.abs(difficultyRank(b.difficulty) - rankTarget);
    if (da !== db) return da - db;
    return difficultyRank(a.difficulty) - difficultyRank(b.difficulty);
  });
}

function createVariedSlotOrder(count: number): number[] {
  const slots: number[] = [];
  while (slots.length < count) {
    const block = shuffleArray([0, 1, 2, 3]);
    if (slots.length > 0 && block[0] === slots[slots.length - 1]) {
      [block[0], block[1]] = [block[1], block[0]];
    }
    slots.push(...block);
  }
  return slots.slice(0, count);
}

function pickBalancedPairs(
  candidates: Question[],
  perPlayerCount: number,
  difficulty: DifficultyLevel,
  usedIds: Set<string>,
  progressive = false
): { razmik: Question[]; gayane: Question[] } {
  const available = shuffleArray(candidates.filter((q) => !usedIds.has(q.id)));
  const ordered = progressive
    ? [...available].sort((a, b) => difficultyRank(a.difficulty) - difficultyRank(b.difficulty))
    : sortByTargetDifficulty(available, difficulty);

  const razmikSlots = createVariedSlotOrder(perPlayerCount);
  const gayaneSlots = createVariedSlotOrder(perPlayerCount);

  const razmik: Question[] = [];
  const gayane: Question[] = [];

  for (let i = 0; i < ordered.length && (razmik.length < perPlayerCount || gayane.length < perPlayerCount); i += 2) {
    const qA = ordered[i];
    const qB = ordered[i + 1];
    if (!qA || !qB) break;
    usedIds.add(qA.id);
    usedIds.add(qB.id);
    if (razmik.length < perPlayerCount) {
      razmik.push(prepareQuestionOptions(qA, razmikSlots[razmik.length]));
    }
    if (gayane.length < perPlayerCount) {
      gayane.push(prepareQuestionOptions(qB, gayaneSlots[gayane.length]));
    }
  }

  return { razmik, gayane };
}

export function buildRoundPlans(params: {
  scope: PlayScope;
  difficulty: DifficultyLevel;
  tenseFilter: TenseFilter;
  questionsPerPlayer: number;
  mistakeIds?: string[];
}): RoundPlan[] {
  const { scope, difficulty, tenseFilter, questionsPerPlayer, mistakeIds = [] } = params;
  const usedIds = new Set<string>();

  const filterByTense = (q: Question) =>
    tenseFilter === 'todos' ? true : q.tense === tenseFilter;

  if (scope === 'repaso') {
    const mistakePool = QUESTION_BANK.filter(
      (q) => mistakeIds.includes(q.id) && filterByTense(q)
    );
    const fallbackPool = QUESTION_BANK.filter(filterByTense);
    const combined =
      mistakePool.length >= 4
        ? [...mistakePool, ...fallbackPool.filter((q) => !mistakeIds.includes(q.id))]
        : fallbackPool;
    const count = Math.min(questionsPerPlayer, Math.floor(combined.length / 2));
    const pairs = pickBalancedPairs(combined, Math.max(2, count), difficulty, usedIds);
    return [
      {
        roundIndex: 0,
        mode: pairs.razmik[0]?.mode ?? 'elige',
        razmikQuestions: pairs.razmik,
        gayaneQuestions: pairs.gayane,
        isFinalChallenge: false,
      },
    ];
  }

  const modesToPlay: GameModeId[] =
    scope === 'torneo'
      ? ['elige', 'traduce', 'corrige', 'viaje', 'batalla', 'desafio']
      : [scope];

  return modesToPlay.map((mode, idx) => {
    const modePool = QUESTION_BANK.filter((q) => q.mode === mode && filterByTense(q));
    const fallbackPool =
      modePool.length >= 6
        ? modePool
        : QUESTION_BANK.filter((q) => q.mode === mode);

    const isFinal = mode === 'desafio';
    const perPlayer = isFinal
      ? Math.min(10, Math.floor(fallbackPool.length / 2))
      : Math.min(questionsPerPlayer, Math.floor(fallbackPool.length / 2));

    const pairs = pickBalancedPairs(
      fallbackPool,
      Math.max(2, perPlayer),
      difficulty,
      usedIds,
      mode === 'batalla'
    );

    return {
      roundIndex: idx,
      mode,
      razmikQuestions: pairs.razmik,
      gayaneQuestions: pairs.gayane,
      isFinalChallenge: isFinal,
    };
  });
}

export function buildTieBreakerRound(
  difficulty: DifficultyLevel,
  tenseFilter: TenseFilter,
  excludeIds: string[]
): RoundPlan {
  const used = new Set(excludeIds);
  const pool = QUESTION_BANK.filter(
    (q) => !used.has(q.id) && (tenseFilter === 'todos' || q.tense === tenseFilter)
  );
  const safePool = pool.length >= 6 ? pool : QUESTION_BANK;
  const pairs = pickBalancedPairs(safePool, 3, difficulty, used);
  return {
    roundIndex: 99,
    mode: 'desafio',
    razmikQuestions: pairs.razmik,
    gayaneQuestions: pairs.gayane,
    isFinalChallenge: false,
    isTieBreaker: true,
  };
}
